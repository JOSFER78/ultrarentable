export interface CriticalDifferenceMetric {
  key: string;
  title: string;
  summary: string;
  accounts_breakdown: Record<
    string,
    {
      badge: string;
      is_best: boolean;
      is_worst: boolean;
      explanation: string;
    }
  >;
}

export interface ComparisonAnalysisResult {
  accounts: PropFirmAccount[];
  cheapest_entry_account_id: string;
  safest_drawdown_account_id: string;
  fastest_payout_account_id: string;
  most_bot_friendly_account_id: string;
  dealbreakers: {
    account_id: string;
    firm_name: string;
    reason: string;
  }[];
  critical_differences: CriticalDifferenceMetric[];
}

export function generateCriticalDifferencesReport(
  accounts: PropFirmAccount[]
): ComparisonAnalysisResult {
  if (!accounts || accounts.length === 0) {
    return {
      accounts: [],
      cheapest_entry_account_id: "",
      safest_drawdown_account_id: "",
      fastest_payout_account_id: "",
      most_bot_friendly_account_id: "",
      dealbreakers: [],
      critical_differences: [],
    };
  }

  const cheapest = [...accounts].sort((a, b) => a.total_pass_cost_usd - b.total_pass_cost_usd)[0];
  const safest = accounts.find((a) => a.drawdown_type === "STATIC") ||
    accounts.find((a) => a.drawdown_type === "EOD_TRAILING") ||
    accounts[0];
  const fastest = accounts.find((a) => a.payout_frequency === "DAY_1_ON_DEMAND") ||
    accounts.find((a) => a.payout_frequency === "SAME_DAY_BUSINESS") ||
    accounts[0];
  const mostBotFriendly = accounts.find((a) => a.bot_policy === "ALLOWED_100") || accounts[0];

  const dealbreakers: { account_id: string; firm_name: string; reason: string }[] = [];
  accounts.forEach((acc) => {
    if (acc.drawdown_type === "INTRADAY_TRAILING") {
      dealbreakers.push({
        account_id: acc.id,
        firm_name: acc.firm_name,
        reason: `⚠️ ${acc.firm_name} (${acc.program_name}) utiliza Trailing Drawdown Intradía sobre picos flotantes no realizados, aumentando el riesgo de quiebra durante retrocesos.`,
      });
    }
    if (acc.bot_policy === "PROHIBITED") {
      dealbreakers.push({
        account_id: acc.id,
        firm_name: acc.firm_name,
        reason: `❌ ${acc.firm_name} (${acc.program_name}) prohíbe terminantemente el uso de bots o asesores expertos (EAs) en cuentas financiadas.`,
      });
    }
    if (acc.trade_duration_10s_rule) {
      dealbreakers.push({
        account_id: acc.id,
        firm_name: acc.firm_name,
        reason: `⏱️ ${acc.firm_name} (${acc.program_name}) exige que >50% de las operaciones duren más de 10 segundos para autorizar retiros.`,
      });
    }
    if (acc.firm_slug === "fasttrack") {
      dealbreakers.push({
        account_id: acc.id,
        firm_name: acc.firm_name,
        reason: `🚨 ADVERTENCIA FORENSE: Fast Track Trading cesó sus operaciones en noviembre de 2024 tras insolvencia reportada. No emitir depósitos.`,
      });
    }
  });

  const diffMetrics: CriticalDifferenceMetric[] = [
    {
      key: "cost_structure",
      title: "Coste Real de Entrada & Activación ($TCO$)",
      summary: "Compara el desembolso total (Examen + Cuota de Activación al aprobar).",
      accounts_breakdown: accounts.reduce((acc, a) => {
        const isBest = a.id === cheapest.id;
        const hasZeroFee = a.activation_fee_usd === 0;
        acc[a.id] = {
          badge: `$${a.total_pass_cost_usd.toFixed(2)} USD`,
          is_best: isBest,
          is_worst: a.activation_fee_usd > 140,
          explanation: hasZeroFee
            ? `$0 de cuota de activación. Solo pagas $${a.exam_price_promo_usd.toFixed(2)} USD por la prueba.`
            : `Examen rebajado a $${a.exam_price_promo_usd.toFixed(2)} USD + $${a.activation_fee_usd} USD de activación obligatoria.`,
        };
        return acc;
      }, {} as CriticalDifferenceMetric["accounts_breakdown"]),
    },
    {
      key: "drawdown_mechanics",
      title: "Mecánica de Drawdown & Riesgo de Liquidación",
      summary: "Diferencia entre Drawdown 100% Estático, Fin de Día (EOD) e Intraday Peak.",
      accounts_breakdown: accounts.reduce((acc, a) => {
        const isStatic = a.drawdown_type === "STATIC";
        const isEod = a.drawdown_type === "EOD_TRAILING";
        const isIntraday = a.drawdown_type === "INTRADAY_TRAILING";
        acc[a.id] = {
          badge: a.drawdown_type_label,
          is_best: isStatic || isEod,
          is_worst: isIntraday,
          explanation: isStatic
            ? "100% Estático: El umbral de liquidación nunca sube, permitiéndote acumular colchón."
            : isEod
            ? "EOD Trailing: Se calcula al cierre diario; las ganancias no cerradas intradía no te perjudican."
            : "Intraday Peak: El suelo de pérdida sube en tiempo real con cada pico de ganancia flotante.",
        };
        return acc;
      }, {} as CriticalDifferenceMetric["accounts_breakdown"]),
    },
    {
      key: "payout_speed",
      title: "Velocidad de Retiro & Colchón Retenido",
      summary: "Rapidez para extraer el primer pago y colchón intocable requerido.",
      accounts_breakdown: accounts.reduce((acc, a) => {
        const isFast = a.payout_frequency === "DAY_1_ON_DEMAND" || a.payout_frequency === "SAME_DAY_BUSINESS";
        acc[a.id] = {
          badge: a.payout_frequency_label,
          is_best: isFast,
          is_worst: a.payout_frequency === "MONTHLY",
          explanation: `Colchón de seguridad obligatorio de $${a.safety_buffer_usd.toLocaleString()} USD antes de poder retirar.`,
        };
        return acc;
      }, {} as CriticalDifferenceMetric["accounts_breakdown"]),
    },
    {
      key: "bots_and_algos",
      title: "Política de Bots, EAs y Trading Automatizado",
      summary: "Permisividad para ejecutar sistemas en VPS y algoritmos.",
      accounts_breakdown: accounts.reduce((acc, a) => {
        const isAllowed = a.bot_policy === "ALLOWED_100";
        const isProhibited = a.bot_policy === "PROHIBITED";
        acc[a.id] = {
          badge: isAllowed ? "100% Permitido" : isProhibited ? "PROHIBIDO" : "Restringido",
          is_best: isAllowed,
          is_worst: isProhibited,
          explanation: a.bot_policy_description,
        };
        return acc;
      }, {} as CriticalDifferenceMetric["accounts_breakdown"]),
    },
  ];

  return {
    accounts,
    cheapest_entry_account_id: cheapest.id,
    safest_drawdown_account_id: safest.id,
    fastest_payout_account_id: fastest.id,
    most_bot_friendly_account_id: mostBotFriendly.id,
    dealbreakers,
    critical_differences: diffMetrics,
  };
}

export function calculateExtractionMetrics(account: PropFirmAccount, targetCapital: number = 10000) {
  const totalEntryCost = account.exam_price_promo_usd + account.activation_fee_usd;
  const netExtractableFirst10k = targetCapital;
  const totalCapitalCommitted = totalEntryCost + account.safety_buffer_usd;
  const netRoiPercentage = ((netExtractableFirst10k - totalEntryCost) / (totalEntryCost + 1e-6)) * 100;

  return {
    totalEntryCost,
    totalCapitalCommitted,
    netExtractableFirst10k,
    netRoiPercentage: Number(netRoiPercentage.toFixed(0)),
    effortTargetToSafetyBuffer: account.profit_target_usd + account.safety_buffer_usd + 1000,
  };
}

export function evaluateDrawdownRisk(account: PropFirmAccount): {
  level: "SAFE" | "MODERATE" | "HIGH_RISK";
  label: string;
  riskClass: string;
} {
  if (account.drawdown_type === "STATIC") {
    return { level: "SAFE", label: "Estático Puro (Bajo Riesgo)", riskClass: "text-emerald-400" };
  }
  if (account.drawdown_type === "EOD_TRAILING") {
    return { level: "MODERATE", label: "EOD Trailing (Riesgo Moderado)", riskClass: "text-cyan-400" };
  }
  return { level: "HIGH_RISK", label: "Intraday Peak (Alto Riesgo)", riskClass: "text-rose-400" };
}
